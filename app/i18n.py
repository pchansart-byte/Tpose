def get_lang(lang: str | None) -> str:
    return lang if lang in LANGUAGES else "es"


def tr(lang: str, key: str, **kwargs) -> str:
    lang = get_lang(lang)
    text = STRINGS.get(key, {}).get(lang)
    if text is None:
        text = STRINGS.get(key, {}).get("es", key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text
